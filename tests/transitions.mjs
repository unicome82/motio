import assert from 'node:assert/strict';
import { readSource as readFile } from './helpers.mjs';
const source = await readFile(new URL('../js/core/view-transition.js', import.meta.url), 'utf8');
const { ViewTransition } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const preference = new EventTarget(); preference.matches = false;
globalThis.document = new EventTarget(); document.hidden = false;
globalThis.window = { matchMedia: () => preference };
let cleared = 0;
const element = { style: { removeProperty: name => { assert.equal(name, 'opacity'); cleared++; } } };
const tweens = [];
window.gsap = { fromTo: (target, from, to) => {
  assert.equal(target, element); assert.deepEqual(from, { opacity: 0 });
  assert.equal(to.duration, .2); assert.equal(to.opacity, 1);
  const tween = { killed: false, to, kill() { this.killed = true; } }; tweens.push(tween); return tween;
} };
const transition = new ViewTransition(element);
transition.enter(); const first = tweens.at(-1);
transition.enter(); assert.equal(first.killed, true); const second = transition.tween;
first.to.onComplete(); assert.equal(transition.tween, second);
second.to.onComplete(); assert.equal(transition.tween, null);
for (let i = 0; i < 100; i++) transition.enter();
assert.equal(tweens.filter(tween => !tween.killed && tween !== second).length, 1);
preference.matches = true; preference.dispatchEvent(new Event('change')); assert.equal(transition.tween, null);
const count = tweens.length; transition.enter(); assert.equal(tweens.length, count);
preference.matches = false; transition.enter();
document.hidden = true; document.dispatchEvent(new Event('visibilitychange')); assert.equal(transition.tween, null);
transition.enter(); assert.equal(transition.tween, null);
document.hidden = false; delete window.gsap; transition.enter(); assert.equal(transition.tween, null);
transition.destroy(); const before = cleared; preference.dispatchEvent(new Event('change')); assert.equal(cleared, before);
console.log('PASS: 200ms fade, rapid-switch cancellation, stale callbacks, live reduced motion, hidden tab, missing GSAP and teardown.');
